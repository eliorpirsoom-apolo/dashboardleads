// Generates prisma/schema.sqlite.prisma from prisma/schema.prisma.
//
// Production runs PostgreSQL (Vercel/Neon); this machine has no Postgres, so
// local dev uses a SQLite file. The models are written to be 100% portable
// (no enums, no Json, no @db.*) — the ONLY difference is the datasource
// block, which this script swaps. Never edit schema.sqlite.prisma by hand.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = path.join(root, "prisma", "schema.prisma");
const dst = path.join(root, "prisma", "schema.sqlite.prisma");

const schema = readFileSync(src, "utf8");

const datasourceRe = /datasource db \{[\s\S]*?\n\}/;
if (!datasourceRe.test(schema)) {
  console.error("gen-sqlite-schema: datasource block not found in schema.prisma");
  process.exit(1);
}

const sqliteDatasource = `datasource db {
  provider = "sqlite"
  url      = env("DATABASE_URL")
}`;

const header = `// AUTO-GENERATED by scripts/gen-sqlite-schema.mjs — DO NOT EDIT.
// Local-dev mirror of schema.prisma with the datasource swapped to SQLite.

`;

writeFileSync(dst, header + schema.replace(datasourceRe, sqliteDatasource));
console.log("schema.sqlite.prisma generated");
